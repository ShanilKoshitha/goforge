func TestApplicationOwnedRepositoryAndQuery(t *testing.T) {
	repository := resource.NewApplicationRepository()
	ctx := context.Background()
	if _, err := repository.BrowseApplication(ctx, resource.Scope{}, resource.ApplicationQuery{Limit: 2}); err == nil { t.Fatal("invalid owner scope accepted") }
	query, err := resource.ParseApplicationQuery("prefix=inbox%2F&limit=1")
	if err != nil || query.Prefix != "inbox/" || query.Limit != 1 { t.Fatalf("custom query = %+v %v", query, err) }
	page, err := repository.BrowseApplication(ctx, resource.OwnerScope(9), query)
	if err != nil || len(page.Items) != 1 || page.Items[0].ID != 1 || !page.HasNext { t.Fatalf("custom prefix preview = %+v %v", page, err) }
	for _, raw := range []string{"q=inbox", "prefix=a&prefix=b", "prefix=%FF", "prefix=%00", "prefix=%", "limit=6", "limit=0"} {
		if _, err := resource.ParseApplicationQuery(raw); err == nil { t.Fatalf("custom query accepted %q", raw) }
	}
	options := resource.DefaultListOptions()
	options.Search, options.Sort, options.Direction, options.PerPage = "inbox", "name", "asc", 1
	page, err = repository.Browse(ctx, resource.OwnerScope(9), options)
	if err != nil || len(page.Items) != 1 || page.Items[0].ID != 1 || !page.HasNext { t.Fatalf("generated repository contract failed on custom backend: %+v %v", page, err) }
	options.Page = 2
	page, err = repository.Browse(ctx, resource.OwnerScope(9), options)
	if err != nil || len(page.Items) != 1 || page.Items[0].ID != 2 || page.HasNext || !page.HasPrevious { t.Fatalf("custom backend pagination = %+v %v", page, err) }
	created, err := repository.Create(ctx, resource.OwnerScope(9), resource.Attributes{Name: "inbox/created"})
	if err != nil || created.UserID != 9 || created.Version != 1 { t.Fatalf("custom create = %+v %v", created, err) }
	if _, err := repository.Find(ctx, resource.OwnerScope(27), created.ID); !errors.Is(err, resource.ErrNotFound) { t.Fatalf("foreign read = %v", err) }
	version := created.Version
	updated, err := repository.Update(ctx, resource.OwnerScope(9), created.ID, resource.Attributes{Name: "inbox/updated"}, &version)
	if err != nil || updated.Version != 2 || updated.Name != "inbox/updated" { t.Fatalf("custom update = %+v %v", updated, err) }
	if _, err := repository.Update(ctx, resource.OwnerScope(9), created.ID, resource.Attributes{Name: "stale"}, &version); !errors.Is(err, resource.ErrStale) { t.Fatalf("stale custom update = %v", err) }
	if err := repository.Delete(ctx, resource.OwnerScope(27), created.ID); !errors.Is(err, resource.ErrNotFound) { t.Fatalf("foreign delete = %v", err) }
	if err := repository.Delete(ctx, resource.OwnerScope(9), created.ID); err != nil { t.Fatal(err) }
	if _, err := repository.Find(ctx, resource.OwnerScope(9), created.ID); !errors.Is(err, resource.ErrNotFound) { t.Fatalf("custom delete did not persist: %v", err) }
}

