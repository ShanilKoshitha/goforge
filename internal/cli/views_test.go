func TestCompileProjectViewsUpdatesManagedArtifact(t *testing.T) {
	root := projectRoot(t)
	directory := filepath.Join(t.TempDir(), "webapp")
	if err := createProject(newOptions{directory: directory, module: "example.com/webapp", replace: root}); err != nil {
		t.Fatal(err)
	}
	t.Chdir(directory)
	page := filepath.Join("resources", "views", "pages", "welcome.forge.html")
	source, err := os.ReadFile(page)
	if err != nil {
		t.Fatal(err)
	}
	updated := strings.Replace(string(source), "@endsection", "<p>Recompiled</p>\n@endsection", 1)
	if err := os.WriteFile(page, []byte(updated), 0o644); err != nil {
		t.Fatal(err)
	}
	var output bytes.Buffer
	if err := Run([]string{"views:compile"}, &output, &output); err != nil {
		t.Fatal(err)
	}
	artifact, err := os.ReadFile(filepath.FromSlash(generatedViewsPath))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(artifact), "Recompiled") || !strings.Contains(output.String(), "updated resources/views/views_gen.go") {
		t.Fatalf("compiled artifact was not updated:\n%s", artifact)
	}
}

